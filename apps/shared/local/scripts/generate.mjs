import { readFileSync, writeFileSync } from 'node:fs';

const contract = new URL('../../contract/src/', import.meta.url);
const bindings = readFileSync(new URL('bindings.ts', contract), 'utf8');
const kinds = JSON.parse(
  readFileSync(new URL('commands.json', contract), 'utf8'),
);

const block = bindings.slice(
  bindings.indexOf('export const commands = {'),
  bindings.indexOf('\n}', bindings.indexOf('export const commands = {')),
);
const parameters = [
  ...block.matchAll(
    /^\t(\w+): \(.*?\) => __TAURI_INVOKE<.*>\("\w+"(?:, \{ ([\w, ]+) \})?\),$/gm,
  ),
].map(([, name, args]) => [name, args ? args.split(', ') : []]);

const literal = (names) =>
  `[${names.map((name) => `'${name}'`).join(', ')}] as const`;

writeFileSync(
  new URL('../src/catalog.ts', import.meta.url),
  `// Generated by scripts/generate.mjs from the contract. Run \`pnpm generate\` after the contract changes.

export const parameters = {
${parameters.map(([name, args]) => `  ${name}: ${literal(args)},`).join('\n')}
};

export const mutations = ${literal(kinds.mutations)};

export const reads = ${literal(kinds.reads)};

export const deviceOnly = ${literal(kinds.deviceOnly)};
`,
);
