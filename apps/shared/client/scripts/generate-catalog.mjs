import { readFileSync, writeFileSync } from 'node:fs';

const types = new URL('../src/types/', import.meta.url);
const bindings = readFileSync(new URL('bindings.ts', types), 'utf8');
const kinds = JSON.parse(readFileSync(new URL('commands.json', types), 'utf8'));

const block = bindings.slice(
  bindings.indexOf('export const commands = {'),
  bindings.indexOf('\n}', bindings.indexOf('export const commands = {')),
);
const parameters = [
  ...block.matchAll(
    /^\t(\w+): \(.*?\) => __TAURI_INVOKE<.*>\("\w+"(?:, \{ ([\w, ]+) \})?\),$/gm,
  ),
].map(([, name, args]) => [name, args ? args.split(', ') : []]);

const literal = (names) =>
  `[${names.map((name) => `'${name}'`).join(', ')}] as const`;

writeFileSync(
  new URL('../src/local/catalog.ts', import.meta.url),
  `// Generated by scripts/generate-catalog.mjs from the types. Run \`pnpm generate:catalog\` after the types change.

export const parameters = {
${parameters.map(([name, args]) => `  ${name}: ${literal(args)},`).join('\n')}
};

export const mutations = ${literal(kinds.mutations)};

export const reads = ${literal(kinds.reads)};

export const deviceOnly = ${literal(kinds.deviceOnly)};
`,
);
